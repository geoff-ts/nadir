// Builds src/c/sky_data.h: the twelve zodiac constellations as ecliptic
// (J2000) longitude/latitude vertices and line segments.
//
//   node tools/gen-sky-data.mjs path/to/constellations.lines.json
//
// Input: d3-celestial's data/constellations.lines.json (BSD-3, Olaf Frohn),
// https://github.com/ofrohn/d3-celestial. Coordinates are RA (degrees,
// -180..180) and Dec. Output units: hundredths of a degree.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ZODIAC = [
  ['Ari', 'ARIES'],
  ['Tau', 'TAURUS'],
  ['Gem', 'GEMINI'],
  ['Cnc', 'CANCER'],
  ['Leo', 'LEO'],
  ['Vir', 'VIRGO'],
  ['Lib', 'LIBRA'],
  ['Sco', 'SCORPIUS'],
  ['Sgr', 'SAGITTARIUS'],
  ['Cap', 'CAPRICORNUS'],
  ['Aqr', 'AQUARIUS'],
  ['Psc', 'PISCES'],
]

const OBLIQUITY = (23.4392911 * Math.PI) / 180
const rad = (d) => (d * Math.PI) / 180
const deg = (r) => (r * 180) / Math.PI

function toEcliptic(raDeg, decDeg) {
  const ra = rad(raDeg)
  const dec = rad(decDeg)
  const lon = Math.atan2(
    Math.sin(ra) * Math.cos(OBLIQUITY) + Math.tan(dec) * Math.sin(OBLIQUITY),
    Math.cos(ra),
  )
  const lat = Math.asin(
    Math.sin(dec) * Math.cos(OBLIQUITY) -
      Math.cos(dec) * Math.sin(OBLIQUITY) * Math.sin(ra),
  )
  return { lon: (deg(lon) + 360) % 360, lat: deg(lat) }
}

const input = process.argv[2]
if (!input) {
  console.error('usage: node gen-sky-data.mjs constellations.lines.json')
  process.exit(1)
}
const data = JSON.parse(readFileSync(input, 'utf8'))

const vertices = []
const vertexIndex = new Map()
const segments = []
const ranges = []

for (const [id] of ZODIAC) {
  const feature = data.features.find((f) => f.id === id)
  if (!feature) throw new Error(`constellation ${id} not in input`)
  const first = segments.length
  for (const line of feature.geometry.coordinates) {
    let previous = null
    for (const [ra, dec] of line) {
      const key = `${ra.toFixed(4)},${dec.toFixed(4)}`
      let index = vertexIndex.get(key)
      if (index === undefined) {
        const { lon, lat } = toEcliptic(ra, dec)
        index = vertices.length
        vertices.push({ lon: Math.round(lon * 100) % 36000, lat: Math.round(lat * 100) })
        vertexIndex.set(key, index)
      }
      if (previous !== null && previous !== index) segments.push([previous, index])
      previous = index
    }
  }
  ranges.push([first, segments.length - first])
}

if (vertices.length > 255) throw new Error('vertex indices no longer fit in uint8_t')

const lines = []
lines.push('// Generated by tools/gen-sky-data.mjs - do not edit by hand.')
lines.push('// Zodiac constellation lines: ecliptic J2000, hundredths of a degree.')
lines.push('// Source: d3-celestial constellations.lines.json (BSD-3-Clause).')
lines.push('#pragma once')
lines.push('#include <stdint.h>')
lines.push('')
lines.push(`#define SKY_VERTEX_COUNT ${vertices.length}`)
lines.push(`#define SKY_SEGMENT_COUNT ${segments.length}`)
lines.push('')
lines.push('typedef struct { uint16_t lon; int16_t lat; } SkyVertex;')
lines.push('typedef struct { uint8_t from; uint8_t to; } SkySegment;')
lines.push('')
lines.push('static const SkyVertex SKY_VERTICES[SKY_VERTEX_COUNT] = {')
for (let i = 0; i < vertices.length; i += 6) {
  lines.push(
    '  ' +
      vertices
        .slice(i, i + 6)
        .map((v) => `{${v.lon}, ${v.lat}}`)
        .join(', ') +
      ',',
  )
}
lines.push('};')
lines.push('')
lines.push('static const SkySegment SKY_SEGMENTS[SKY_SEGMENT_COUNT] = {')
for (let i = 0; i < segments.length; i += 8) {
  lines.push(
    '  ' +
      segments
        .slice(i, i + 8)
        .map(([a, b]) => `{${a}, ${b}}`)
        .join(', ') +
      ',',
  )
}
lines.push('};')
lines.push('')

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'c', 'sky_data.h')
writeFileSync(out, lines.join('\n'))
console.log(`${vertices.length} vertices, ${segments.length} segments -> ${out}`)
for (let i = 0; i < ZODIAC.length; i++) {
  console.log(ZODIAC[i][1].padEnd(12), 'segments', ranges[i][0], '+', ranges[i][1])
}
